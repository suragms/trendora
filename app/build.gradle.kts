// ============================================================
// SECURE API KEY CONFIGURATION
// Read secrets from the git-ignored `local.properties` file at
// configuration time and expose them via BuildConfig fields.
// This keeps API keys out of Kotlin source and out of version control.
// ============================================================
val localProperties = Properties().apply {
    val file = rootProject.file("local.properties")
    if (file.exists()) {
        FileInputStream(file).use { load(it) }
    }
}

fun secretFromLocalProperties(name: String): String =
    localProperties.getProperty(name)?.trim() ?: ""

